  OWNER: 'badge-lime',
  TRAINER: 'badge-orange',
  DESK: 'badge-purple',
  ADMIN: 'badge-purple',
  SYSTEM: 'badge-blue',
  STAFF: 'badge-lime',
  ATHLETE: 'badge-blue',
  NEW: 'badge-blue',
